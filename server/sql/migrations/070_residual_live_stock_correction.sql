-- Current post-rebuild balance per (warehouse, material).
DROP TEMPORARY TABLE IF EXISTS _cur;
CREATE TEMPORARY TABLE _cur AS
SELECT sl.warehouse_id, sl.material_id, sl.balance_qty AS cur_qty, sl.uom
FROM stock_ledger sl
JOIN (SELECT warehouse_id, material_id, MAX(transaction_date) md
        FROM stock_ledger GROUP BY warehouse_id, material_id) d
  ON d.warehouse_id=sl.warehouse_id AND d.material_id=sl.material_id AND d.md=sl.transaction_date
JOIN (SELECT warehouse_id, material_id, transaction_date, MAX(id) mid
        FROM stock_ledger GROUP BY warehouse_id, material_id, transaction_date) i
  ON i.warehouse_id=sl.warehouse_id AND i.material_id=sl.material_id
 AND i.transaction_date=sl.transaction_date AND i.mid=sl.id;

-- Post one residual Stock Adjustment where current balance != target.
INSERT INTO stock_ledger
  (transaction_date, transaction_type, reference_type, reference_id, reference_no,
   warehouse_id, material_id, uom, in_qty, in_value, out_qty, out_value,
   unit_cost, amount, opening_qty, opening_value, balance_qty, balance_value, remarks, created_by)
SELECT
  CURDATE(), 'Stock Adjustment', 'stock_correction', 0, 'SC-070',
  t.warehouse_id, t.material_id, c.uom,
  CASE WHEN (t.target_qty - COALESCE(c.cur_qty,0)) > 0 THEN (t.target_qty - COALESCE(c.cur_qty,0)) ELSE 0 END,
  CASE WHEN (t.target_qty - COALESCE(c.cur_qty,0)) > 0 THEN ROUND((t.target_qty - COALESCE(c.cur_qty,0)) * t.avg_rate, 2) ELSE 0 END,
  CASE WHEN (t.target_qty - COALESCE(c.cur_qty,0)) < 0 THEN ABS(t.target_qty - COALESCE(c.cur_qty,0)) ELSE 0 END,
  CASE WHEN (t.target_qty - COALESCE(c.cur_qty,0)) < 0 THEN ROUND(ABS(t.target_qty - COALESCE(c.cur_qty,0)) * t.avg_rate, 2) ELSE 0 END,
  t.avg_rate, ROUND(ABS(t.target_qty - COALESCE(c.cur_qty,0)) * t.avg_rate, 2),
  0, 0, 0, 0,
  'Opening balance correction (SC-070)', NULL
FROM _tgt t
LEFT JOIN _cur c ON c.warehouse_id=t.warehouse_id AND c.material_id=t.material_id
JOIN warehouses w ON w.id=t.warehouse_id
WHERE ABS(t.target_qty - COALESCE(c.cur_qty,0)) > 0.0015;

